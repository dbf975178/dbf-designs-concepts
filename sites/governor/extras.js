/* Round 2 behavior: notification bar, timed pop-up, countdown, pledge counter, lightbox, video dialog, copy buttons.
   Loads after site.js (which defines window.I18N) and before shared.js. Nothing is sent anywhere. */
(function () {
  "use strict";
  var doc = document, root = doc.documentElement;
  var $ = function (s, c) { return (c || doc).querySelector(s); };
  var $$ = function (s, c) { return Array.prototype.slice.call((c || doc).querySelectorAll(s)); };
  var store = {
    get: function (k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set: function (k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  };
  function lang() { return root.getAttribute("lang") === "es" ? "es" : "en"; }
  function tr(k) { var d = window.I18N; return (d[lang()] && d[lang()][k]) || d.en[k] || k; }
  var K = window.I18N_X || {};
  var page = (doc.body.getAttribute("data-page") || "");

  /* Copy buttons: handled here so the feedback is translated. Runs before shared.js binds its own copy handler. */
  $$("[data-copy]").forEach(function (b) {
    b.addEventListener("click", function (e) {
      e.stopImmediatePropagation();
      var text = b.getAttribute("data-copy"), label = $("[data-copy-label]", b);
      var done = function () {
        if (!label) return;
        var orig = label.getAttribute("data-i18n");
        label.setAttribute("data-i18n", K.copied); label.textContent = tr(K.copied);
        clearTimeout(b._t);
        b._t = setTimeout(function () { label.setAttribute("data-i18n", orig); label.textContent = tr(orig); }, 1600);
      };
      if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(text).then(done, done); else done();
    }, true);
  });

  /* Notification bar */
  var close = $("[data-nbar-close]");
  if (close) close.addEventListener("click", function () {
    store.set("gov:bar", "1"); root.classList.add("bar-off");
    var lg = $(".hdr .logo"); if (lg) lg.focus();
  });

  /* Timed pop-up: once after about 12 seconds or on exit intent. Never on donate pages. */
  var pop = $("#signup-pop");
  if (pop && page !== "donate" && store.get("gov:pop") !== "1") {
    var shown = false, timer = 0;
    var open = function () {
      if (shown) return;
      var typing = doc.activeElement && /^(INPUT|TEXTAREA|SELECT)$/.test(doc.activeElement.tagName);
      if (typing || $$("dialog[open]").length) { timer = setTimeout(open, 8000); return; }
      shown = true; store.set("gov:pop", "1");
      if (typeof pop.showModal === "function") pop.showModal(); else pop.setAttribute("open", "");
    };
    timer = setTimeout(open, 12000);
    if (window.matchMedia("(hover:hover) and (pointer:fine)").matches) {
      doc.addEventListener("mouseout", function (e) { if (!e.relatedTarget && e.clientY <= 0) { clearTimeout(timer); open(); } });
    }
  }
  doc.addEventListener("gov:success", function (e) {
    if (e.target && e.target.closest && e.target.closest("#signup-pop")) store.set("gov:pop", "1");
  });

  /* Countdown */
  $$("[data-countdown]").forEach(function (el) {
    var target = new Date(el.getAttribute("data-countdown")), d = $("[data-cd=d]", el), h = $("[data-cd=h]", el), m = $("[data-cd=m]", el);
    var tick = function () {
      var ms = Math.max(0, target - new Date());
      d.textContent = Math.floor(ms / 864e5);
      h.textContent = String(Math.floor(ms % 864e5 / 36e5)).padStart(2, "0");
      m.textContent = String(Math.floor(ms % 36e5 / 6e4)).padStart(2, "0");
    };
    tick(); setInterval(tick, 30000);
  });

  /* Pledge counter */
  var pledge = $("[data-pledge]");
  if (pledge) {
    var n = 18462, goal = 25000, out = $("[data-signers]", pledge), bar = $("[data-meter]", pledge), meter = $(".meter", pledge);
    pledge.addEventListener("gov:success", function () {
      n += 1; out.textContent = n.toLocaleString("en-US");
      var pct = Math.min(100, n / goal * 100); bar.style.width = pct.toFixed(1) + "%";
      meter.setAttribute("aria-label", tr(K.progress).replace("{p}", pct.toFixed(1)));
    });
  }

  /* Lightbox */
  var lb = $("#lightbox");
  if (lb) $$("[data-lb]").forEach(function (b) {
    b.addEventListener("click", function () {
      var im = $("img", b), big = $("[data-lb-img]", lb), cap = $("[data-lb-cap]", lb);
      big.src = b.getAttribute("data-lb"); big.alt = im.alt; cap.textContent = im.alt;
      if (typeof lb.showModal === "function") lb.showModal(); else lb.setAttribute("open", "");
    });
  });

  /* Video dialog (poster tiles only, no real video) */
  var vd = $("#video");
  if (vd) $$("[data-video-open]").forEach(function (b) {
    b.addEventListener("click", function () {
      var t = $("[data-vt]", b) || (b.parentElement && $("[data-vt]", b.parentElement));
      $("[data-video-title]", vd).textContent = t ? t.textContent : "";
      if (typeof vd.showModal === "function") vd.showModal(); else vd.setAttribute("open", "");
    });
  });
})();
