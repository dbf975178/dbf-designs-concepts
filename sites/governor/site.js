  function signGen() {
    var cv = $("#sign-canvas"); if (!cv) return;
    var form = $("[data-sign-form]"), ctx = cv.getContext("2d"), W = cv.width, H = cv.height, M = 130, raf = 0;
    var val = function (n) { var el = form.elements[n]; return el ? el.value : ""; };
    function fit(text, font, maxW, start) {
      ctx.font = start + "px " + font; var w = ctx.measureText(text).width;
      return Math.min(start, Math.floor(start * maxW / w));
    }
    function track(text, x, y, sp) {
      for (var i = 0; i < text.length; i++) { ctx.fillText(text[i], x, y); x += ctx.measureText(text[i]).width + sp; }
    }
    function draw() {
      var c = COLORS[val("variant") || "ink"] || COLORS.ink, L = POSTER[val("lang") === "es" ? "es" : "en"];
      var slab = "'Alfa Slab One', Georgia, serif", sans = "'Work Sans', system-ui, sans-serif";
      ctx.clearRect(0, 0, W, H); ctx.fillStyle = c.bg; ctx.fillRect(0, 0, W, H);
      // halftone corner
      var step = 46, ca = Math.SQRT1_2, n = Math.ceil((W + H) / step);
      ctx.fillStyle = c.dot;
      for (var i = -n; i < n; i++) for (var j = -n; j < n; j++) {
        var x = (i + j) * step * ca + W / 2, y = (i - j) * step * ca + H / 2;
        if (x < 0 || x > W || y < 0 || y > H) continue;
        var d = Math.hypot(x - W, y - H * 0.38), v = Math.max(0, 1 - d / 1700), r = v * v * step * 0.7;
        if (r > 0.8) { ctx.beginPath(); ctx.arc(x, y, r, 0, 6.2832); ctx.fill(); }
      }
      ctx.textBaseline = "alphabetic"; ctx.textAlign = "left";
      // top line
      var street = val("street").trim(), top = (street ? L.backs.replace("{s}", street) : L.neighbors).toUpperCase();
      ctx.fillStyle = c.fg; ctx.font = "700 78px " + sans;
      var sp = 10, tw = 0; for (var k = 0; k < top.length; k++) tw += ctx.measureText(top[k]).width + sp;
      if (tw > W - 2 * M) { var sz = Math.floor(78 * (W - 2 * M) / tw); ctx.font = "700 " + sz + "px " + sans; sp = 6; }
      track(top, M, 230, sp);
      // name
      var nameT = "ASHCOMBE", ns = fit(nameT, slab, W - 2 * M, 330);
      ctx.font = ns + "px " + slab; ctx.fillStyle = c.fg; ctx.fillText(nameT, M, 230 + 40 + ns * 0.78);
      var yName = 230 + 40 + ns * 0.78;
      var gov = L.forGov.toUpperCase(), gs = fit(gov, slab, W - 2 * M, 150);
      ctx.font = gs + "px " + slab; ctx.fillStyle = c.hot; ctx.fillText(gov, M, yName + 30 + gs * 0.9);
      var yRule = yName + 30 + gs * 0.9 + 60;
      ctx.fillStyle = c.fg; ctx.fillRect(M, yRule, W - 2 * M, 26);
      // tagline
      var lines = L.lines.map(function (s) { return s.toUpperCase(); }), size = 295;
      lines.forEach(function (s) { size = Math.min(size, fit(s, slab, W - 2 * M, 295)); });
      ctx.font = size + "px " + slab;
      var y0 = yRule + 26 + 40 + size * 0.74, pitch = size * 0.94;
      lines.forEach(function (s, idx) { ctx.fillStyle = idx === 3 ? c.hot : c.fg; ctx.fillText(s, M, y0 + idx * pitch); });
      // name tag
      var who = val("name").trim();
      if (who) {
        var tag = who.toUpperCase(); ctx.font = "700 76px " + sans;
        var tsz = fit(tag, sans, W - 2 * M - 80, 76); ctx.font = "700 " + tsz + "px " + sans;
        var tw2 = ctx.measureText(tag).width + 80, ty = H - 410;
        ctx.fillStyle = c.hot; ctx.fillRect(M + 14, ty + 14, tw2, 124);
        ctx.fillStyle = c.fg; ctx.fillRect(M, ty, tw2, 124);
        ctx.fillStyle = c.bg; ctx.fillText(tag, M + 40, ty + 124 / 2 + tsz * 0.35);
      }
      // legal
      ctx.fillStyle = c.fg; ctx.font = "600 36px " + sans;
      wrap(L.paid, M, H - 200, W - 2 * M, 46);
      ctx.globalAlpha = 0.8; ctx.font = "500 30px " + sans; ctx.fillText(L.fict, M, H - 70); ctx.globalAlpha = 1;
    }
    function wrap(text, x, y, maxW, lh) {
      var words = text.split(" "), line = "", yy = y;
      words.forEach(function (w) {
        var test = line ? line + " " + w : w;
        if (ctx.measureText(test).width > maxW && line) { ctx.fillText(line, x, yy); line = w; yy += lh; } else line = test;
      });
      ctx.fillText(line, x, yy);
    }
    function queue() { cancelAnimationFrame(raf); raf = requestAnimationFrame(draw); }
    form.addEventListener("input", queue); form.addEventListener("change", queue);
    var ready = (doc.fonts && doc.fonts.load) ? Promise.all([doc.fonts.load("100px 'Alfa Slab One'"), doc.fonts.load("700 40px 'Work Sans'"), doc.fonts.load("500 40px 'Work Sans'")]).catch(function () {}) : Promise.resolve();
    draw(); ready.then(function () { draw(); if (doc.fonts && doc.fonts.ready) doc.fonts.ready.then(draw); });
    $("[data-sign-download]").addEventListener("click", function () {
      var st = $("[data-sign-status]"), file = "ashcombe-yard-sign-" + (val("variant") || "ink") + ".png";
      draw();
      cv.toBlob(function (blob) {
        if (!blob) { st.textContent = t("sign_fail"); return; }
        var a = doc.createElement("a"), url = URL.createObjectURL(blob);
        a.href = url; a.download = file; doc.body.appendChild(a); a.click(); a.remove();
        setTimeout(function () { URL.revokeObjectURL(url); }, 2000);
        st.textContent = t("sign_saved", { file: file });
      }, "image/png");
    });
    $("[data-sign-reset]").addEventListener("click", function () { form.reset(); form.elements.name.value = "Marisol Okafor"; form.elements.street.value = "Linden Street"; draw(); $("[data-sign-status]").textContent = ""; });
  }

  /* Cut-paper reveals: clip-path hides most of the box, so observe with threshold 0. */
  function cutReveals() {
    var els = $$('[data-reveal="cut"]'); if (!els.length) return;
    if (reduce || !("IntersectionObserver" in window)) { els.forEach(function (e) { e.classList.add("is-in"); }); return; }
    var io = new IntersectionObserver(function (en) {
      en.forEach(function (x) { if (x.isIntersecting) { x.target.classList.add("is-in"); io.unobserve(x.target); } });
    }, { threshold: 0, rootMargin: "0px 0px -12% 0px" });
    els.forEach(function (e) { io.observe(e); });
  }

